    def _extract_key_points(self, analysis_text, category):
        """Extract key points from analysis text"""
        # Simple extraction logic - can be enhanced with NLP
        sentences = analysis_text.split('.')
        key_points = []
        
        for sentence in sentences[:5]:  # Take first 5 sentences
            sentence = sentence.strip()
            if len(sentence) > 20:  # Filter out very short sentences
                key_points.append(sentence)
        
        if not key_points:
            key_points = [
                f"Comprehensive {category} analysis completed",
                "Key insights and trends identified",
                "Strategic recommendations developed",
                "Implementation roadmap created"
            ]
        
        return key_points
    
    def generate_ppt_by_type(self, ppt_type, analysis_data, conversation_id):
        """Generate PPT based on the specified type"""
        type_mapping = {
            'ProductsServices': self.generate_products_services_ppt,
            'MarketClients': self.generate_market_clients_ppt,
            'PerformanceGrowth': self.generate_performance_growth_ppt,
            'StrategyVision': self.generate_strategy_vision_ppt,
            'Proposal': self.generate_proposal_ppt
        }
        
        if ppt_type in type_mapping:
            return type_mapping[ppt_type](analysis_data, conversation_id)
        else:
            raise ValueError(f"Unknown PPT type: {ppt_type}")