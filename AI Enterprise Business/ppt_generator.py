        # Title slide
        self.add_title_slide(prs, "Products & Services Analysis", "Comprehensive Product Portfolio Review")
        
        # Overview slide
        overview_points = [
            "Product portfolio performance analysis",
            "Service delivery metrics and quality assessment",
            "Market positioning and competitive advantages",
            "Customer satisfaction and feedback analysis",
            "Revenue contribution by product/service category"
        ]
        self.add_content_slide(prs, "Analysis Overview", overview_points)
        
        # Key findings slide
        if isinstance(analysis_data, str):
            # Parse the analysis data into key points
            key_points = self._extract_key_points(analysis_data, "products and services")
        else:
            key_points = [
                "Top performing products identified",
                "Service quality improvements recommended",
                "Market expansion opportunities discovered",
                "Customer retention strategies proposed"
            ]
        
        self.add_content_slide(prs, "Key Findings", key_points)
        
        # Recommendations slide
        recommendations = [
            "Optimize high-performing product lines",
            "Enhance service delivery processes",
            "Develop new market entry strategies",
            "Implement customer feedback systems",
            "Focus on profitable service categories"
        ]
        self.add_content_slide(prs, "Strategic Recommendations", recommendations)
        
        # Save the presentation
        filename = f"ppt_ProductsServices_{conversation_id}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.pptx"
        filepath = os.path.join(self.exports_dir, filename)
        prs.save(filepath)
        
        return filepath
    
